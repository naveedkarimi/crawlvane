import { requireAccount } from "@/lib/apiAuth";
import { rateLimit } from "@/lib/rateLimit";
import { db, readJson } from "@/lib/store";
import { GithubError, cleanDir, openFixPr, type PrFile } from "@/lib/githubPr";
import type { GeneratedFix } from "@/lib/reportTypes";
import { BRAND } from "@/lib/brand";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";
export const maxDuration = 90;

/** Where each generated fix goes in the repository. Snippets that need placing by hand go in a folder of their own. */
function filesFor(fixes: GeneratedFix[], dir: string): PrFile[] {
  const slug = BRAND.name.toLowerCase().replace(/[^a-z0-9]+/g, "-");
  const where: Record<string, string> = { robots: `${dir}robots.txt`, llms: `${dir}llms.txt`, sitemap: `${dir}sitemap.xml`, schema: `${slug}/schema.html`, "head-tags": `${slug}/head-tags.html` };
  return fixes.filter((f) => where[f.id] && f.content).map((f) => ({ path: where[f.id], content: f.content }));
}

/** POST { reportId, repo, base?, dir?, token } opens a pull request with the report's fixes. The token isn't stored. */
export async function POST(req: Request) {
  const a = await requireAccount(req);
  if (a instanceof Response) return a;
  if (a.role === "viewer") return Response.json({ error: "Viewers can't open pull requests." }, { status: 403 });
  if (!await rateLimit("githubpr:" + a.org.id, 10)) return Response.json({ error: "Too many pull requests. Try again later." }, { status: 429 });
  const b = (await req.json().catch(() => ({}))) as { reportId?: string; repo?: string; base?: string; dir?: string; token?: string };
  const reportId = String(b.reportId ?? "");
  const { data: link } = await db().from("org_reports").select("report_id").eq("org_id", a.org.id).eq("report_id", reportId).maybeSingle();
  if (!link) return Response.json({ error: "Open this from a report your team ran." }, { status: 404 });
  const report = await readJson<{ url?: string; fixes?: GeneratedFix[] }>("reports", reportId);
  if (!report?.fixes?.length) return Response.json({ error: "This report has no fixes to add." }, { status: 400 });
  try {
    const files = filesFor(report.fixes, cleanDir(b.dir));
    const body = [
      `Fixes generated by ${BRAND.name} for ${report.url ?? "this site"}.`,
      "",
      ...files.map((f) => `- \`${f.path}\``),
      "",
      `Files under \`${BRAND.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}/\` are snippets to paste into your home page's <head>; move them into your templates, then delete the folder.`,
      "Review each file before merging.",
    ].join("\n");
    const pr = await openFixPr({ token: String(b.token ?? "").trim(), repo: String(b.repo ?? "").trim(), base: b.base?.trim(), files, title: `${BRAND.name}: search and AI-readiness fixes`, body });
    return Response.json(pr);
  } catch (e) {
    if (e instanceof GithubError) return Response.json({ error: e.message }, { status: e.status });
    console.error("github-pr", e);
    return Response.json({ error: "We couldn't reach GitHub. Try again." }, { status: 502 });
  }
}
